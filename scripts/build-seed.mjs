// Generates the bundled exercise seed (JSON) and the Supabase seed SQL from exercise-list.mjs.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXERCISES } from './exercise-list.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NAMESPACE = 'spark-lift/global-exercise/';

// Deterministic UUID (v5-style layout) from the exercise name.
function stableUuid(name) {
  const h = createHash('sha1').update(NAMESPACE + name).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const hex = h.subarray(0, 16).toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const names = new Set();
const rows = EXERCISES.map(([name, type, equipment, primary, secondary]) => {
  if (names.has(name)) throw new Error(`Duplicate exercise name: ${name}`);
  names.add(name);
  return { id: stableUuid(name), name, type, equipment, primary_muscle: primary, secondary_muscles: secondary };
});

const jsonPath = resolve(root, 'src/features/exercises/seed.json');
mkdirSync(dirname(jsonPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify(rows, null, 1) + '\n');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const values = rows
  .map((r) => `  (${q(r.id)}, null, ${q(r.name)}, ${q(r.type)}, ${q(r.equipment)}, ${q(r.primary_muscle)}, ${arr(r.secondary_muscles)})`)
  .join(',\n');
const sql = `-- GENERATED by scripts/build-seed.mjs — do not edit by hand.
insert into public.exercises (id, owner_id, name, type, equipment, primary_muscle, secondary_muscles) values
${values}
on conflict (id) do update set
  name = excluded.name, type = excluded.type, equipment = excluded.equipment,
  primary_muscle = excluded.primary_muscle, secondary_muscles = excluded.secondary_muscles;
`;
const sqlPath = resolve(root, 'supabase/seed.sql');
mkdirSync(dirname(sqlPath), { recursive: true });
writeFileSync(sqlPath, sql);

console.log(`Wrote ${rows.length} exercises -> ${jsonPath}, ${sqlPath}`);
